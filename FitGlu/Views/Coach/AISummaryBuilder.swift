import Foundation

enum AISummaryBuilder {
    static func makeDailyPrompt(from m: DailyCoachMetrics, goal: TrainingGoal, rules: CoachRuleOutput) -> String {
        """
        Ты — спортивный врач и тренер по восстановлению.  
        Составь чёткий, персонализированный план на сегодня на основе физиологических данных, учитывая актуальные научные исследования и рекомендации.  
        Ответ должен быть в виде **4 пунктов**: 3 рекомендации и 1 мотивационная фраза.
        Каждый из первых трёх пунктов должен быть коротким, начинаться с глагола в повелительном наклонении (например: "Пройди 7 тыс. шагов", "Избегай тренировок сегодня") и не содержать объяснений.
        Четвёртый пункт — короткая позитивная фраза для мотивации.

        📊 **Текущие данные:**
        • Готовость (общая): \(m.readiness)/100
        • Готовность к тренировке: \((m.trainingReadiness ?? 0))/100 (\(m.trainingReadinessLabel ?? "—"))
        • Время до следующей тренировки: \(String(format: "%.1f", m.nextTrainingInHours ?? 0)) ч
        • Сон: \(m.sleepString) (\(m.sleepMin) мин)
        • Пульс покоя сегодня: \(m.restingHR ?? 0) bpm    Базовый RHR: \(m.baselineHR ?? 0) bpm    HRmax: \(m.hrMax) bpm
        • Вес: \(m.weightString) \(m.weightDeltaString ?? "")
        • Шаги: \(m.steps) / \(m.stepsTarget) (цель)
        • Белок: \(m.proteinG) г / \(m.proteinTarget) г (цель)
        • kкал за тренировки сегодня: \(Int(m.kcal.rounded()))
        • Последняя тренировка: тип \(m.lastTrainingType ?? "—"), прошедшее время \(String(format: "%.1f", m.hoursSinceLastTraining ?? 0)) ч
        • Уровень восстановления (progress): \(m.recoveryProgressString ?? "—")
        • Качество последней тренировки: \((m.lastTrainingScore ?? 0))/100

        🎯 **Цель пользователя:**
        • Goal: \(goal.title) — \(goal.subtitle)

        🧭 **Правила (MVP):**
        • Diagnosis: \(rules.diagnosis)
        • Rest: \(rules.rest.first ?? "—"); \(rules.rest.dropFirst().first ?? "—")
        • Load: \(rules.load)
        • Warning: \(rules.warning)

        ⚙️ **Интерпретация данных (правила для рекомендаций):**
        - Все рекомендации должны основываться на актуальных научных данных и рекомендациях и быть адаптированы под конкретные показатели пользователя и его цель. Избегай шаблонных, слишком общих советов.  
        - Учти цель пользователя: добавь рекомендацию, которая непосредственно поможет продвинуться к этой цели (будь то выносливость, похудение, набор мышц и т.д.).  
        - Придерживайся умеренного подхода: советы не должны быть чрезмерно жёсткими или слишком мягкими (интенсивность рекомендаций при необходимости можно будет настроить отдельно).  
        - Если сон короткий (менее 6 часов) → обязательно добавь совет на восстановление (отдых, ранний отход ко сну, расслабление).  
        - Если пульс покоя заметно выше базового (готовность низкая, recoveryProgress < 100% или trainingReadiness < 60) → добавь пункт, где советуешь избегать тяжёлых/интервальных нагрузок.  
        - Если потребление белка менее 70% от цели → добавь конкретный совет по питанию (увеличить потребление белка и пример приёма пищи).  
        - Если с последней тренировки прошло меньше 12 часов или trainingReadiness < 50 → не планируй сегодня высокоинтенсивную тренировку, максимум лёгкая активность/прогулка.  
        - Если готовность > 70, сон ≥ 7 часов и trainingReadiness ≥ 70 → предложи тренировку (укажи тип нагрузки и примерную длительность).  
        - Если качество последней тренировки (lastTrainingScore) < 40 → добавь рекомендацию снизить интенсивность или уделить внимание технике и восстановлению.  
        - Если качество 40–70 → отметь, что тренировка была средней по качеству, и можно слегка уточнить фокус (например, более ровное распределение зон).  
        - Если качество > 70 → подчеркни, что последняя тренировка прошла хорошо, но всё равно напомни про восстановление и сон.

        💬 **Формат ответа (строго соблюдать):**
        1️⃣ **Что делать:** конкретная основная рекомендация на сегодня (тренировка, шаги, отдых или другое действие).
        2️⃣ **Чего избегать:** чего сегодня лучше не делать (например: "Избегай тяжёлых интервальных тренировок").
        3️⃣ **Что улучшить:** один главный аспект для улучшения (питание, сон, режим шагов, восстановление и т.п.).
        4️⃣ **Мотивация:** одна короткая ободряющая фраза без цифр и анализа.
        """
    }
}
